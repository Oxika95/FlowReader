<#
.SYNOPSIS
  Regenerate .cursor/commands/start-<area>.md and start-<area>-<sub>.md so the slash-command popup
  autocompletes areas and sub-areas as you type (/start-p, /start-plugins-r).

.DESCRIPTION
  Areas and sub-areas come from ../flow-reader-chats/_config/areas.md (text before ';' in the
  Sub-areas cell); the plugins area also gets one sub-area per ../flow-reader-plugins folder with a
  plugin.json. Descriptions come from the `sub:` rows in docs/agent/map.md and plugin manifests.
  The popup shows each file's first sentence and double-escapes angle brackets, so descriptions
  avoid '<', '>' and '. '. Run after editing the area table or map.md tags.

.EXAMPLE
  .\scripts\gen-start-commands.ps1
  .\scripts\gen-start-commands.ps1 -Check   # exit 1 if the commands are stale
#>
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$areasFile = Join-Path $root '..\flow-reader-chats\_config\areas.md'
$pluginsRoot = Join-Path $root '..\flow-reader-plugins'
$mapFile = Join-Path $root 'docs\agent\map.md'
$cmdDir = Join-Path $root '.cursor\commands'
$marker = 'Generated by `scripts/gen-start-commands.ps1`'

if (-not (Test-Path $areasFile)) { Write-Host "No $areasFile; start commands left as they are."; exit 0 }

function Clean($text) {
  ($text -replace '`', '' -replace '[<>]', '' -replace '\.\s', '; ' -replace '\s+', ' ').Trim().TrimEnd('.')
}

$areas = @()
foreach ($line in [IO.File]::ReadAllLines($areasFile)) {
  if ($line -notmatch '^\|\s*`([a-z]+)`\s*\|\s*`([a-z]+)`\s*\|([^|]+)\|[^|]+\|([^|]*)\|') { continue }
  $id, $alias, $label, $subCell = $Matches[1], $Matches[2], $Matches[3], $Matches[4]
  $subs = @($subCell.Split(';')[0].Split(',') | ForEach-Object { $_.Trim() } | Where-Object { $_ -match '^[a-z]+$' })
  $areas += [pscustomobject]@{ Id = $id; Alias = $alias; Label = ($label -replace '\(.*\)', '').Trim(); Subs = $subs }
}

$rows = @{}
$section = $null
foreach ($line in [IO.File]::ReadAllLines($mapFile)) {
  if ($line -match '^## (\S+)') { $section = $Matches[1]; continue }
  if ($section -and $line -match '^\|\s*([a-z, ]+):\s*([^|]+)\|') {
    foreach ($tag in $Matches[1].Split(',')) {
      $key = "$section-$($tag.Trim())"
      if (-not $rows.ContainsKey($key)) { $rows[$key] = @() }
      $rows[$key] += Clean $Matches[2]
    }
  }
}

$plugins = @()
if (Test-Path $pluginsRoot) {
  foreach ($manifest in Get-ChildItem $pluginsRoot -Directory | ForEach-Object { Join-Path $_.FullName 'plugin.json' } | Where-Object { Test-Path $_ }) {
    $json = Get-Content $manifest -Raw | ConvertFrom-Json
    $plugins += [pscustomobject]@{ Id = $json.id; Desc = Clean "$($json.name) plugin: $($json.description)" }
  }
}

function Body($name, $desc, $area, $sub) {
  $target = if ($sub) { "AREA ``$area``, SUB ``$sub``" } else { "AREA ``$area``" }
  "# Start: $name`n`n$desc.`n`n$marker from the area table in ``../flow-reader-chats/_config/areas.md``; do not edit.`n`nRun ``start.md`` in this folder with $target and the arguments as TASK; ask for the task if none was given.`n"
}

$outputs = [ordered]@{}
foreach ($a in $areas) {
  $subs = @($a.Subs)
  $descs = @{}
  foreach ($s in $subs) { $descs[$s] = ($rows["$($a.Id)-$s"] -join '; ') }
  if ($a.Id -eq 'plugins') { foreach ($p in $plugins) { $subs += $p.Id; $descs[$p.Id] = $p.Desc } }
  $desc = if ($subs.Count) { "$($a.Label): type the task, or narrow with " + (($subs | ForEach-Object { "-$_" }) -join ' ') } else { "$($a.Label): type the task" }
  $outputs["start-$($a.Id).md"] = Body "$($a.Id) (alias $($a.Alias))" $desc $a.Id $null
  foreach ($s in $subs) {
    $sd = if ($descs[$s]) { $descs[$s] } else { "$($a.Label), $s" }
    $outputs["start-$($a.Id)-$s.md"] = Body "$($a.Id)-$s" $sd $a.Id $s
  }
}

$stale = @()
foreach ($k in $outputs.Keys) {
  $path = Join-Path $cmdDir $k
  $existing = if (Test-Path $path) { [IO.File]::ReadAllText($path).Replace("`r`n", "`n") } else { $null }
  if ($existing -ne $outputs[$k]) {
    $stale += $k
    if (-not $Check) { [IO.File]::WriteAllText($path, $outputs[$k]) }
  }
}
$orphans = @(Get-ChildItem $cmdDir -Filter 'start-*.md' | Where-Object { $_.Name -notin $outputs.Keys -and (Select-String -Path $_.FullName -SimpleMatch $marker -Quiet) })
if ($Check) {
  if ($stale.Count -or $orphans.Count) { Write-Error "Start commands are stale ($(($stale + @($orphans | ForEach-Object Name)) -join ', ')); run scripts/gen-start-commands.ps1"; exit 1 }
  Write-Host 'Start commands up to date.'
  exit 0
}
$orphans | Remove-Item
Write-Host "Wrote $($stale.Count) of $($outputs.Count) start command(s); removed $($orphans.Count)."
