<#
.SYNOPSIS
  Regenerate docs/agent/index.md (router) and docs/agent/index/*.md (one file per package group):
  every Kotlin file with line count and declarations + line numbers.

.DESCRIPTION
  Package groups: first path segment, or first two segments under ui/ and plugin/. Top-level
  non-private declarations are listed for every file. Files over -MemberThreshold lines also list
  private top-level and member functions so agents can Read a slice instead of the whole file.
  Run after adding, moving, or splitting files.

.EXAMPLE
  .\scripts\gen-agent-index.ps1
  .\scripts\gen-agent-index.ps1 -Check   # exit 1 if the index is stale
#>
param(
  [int]$MemberThreshold = 400,
  [switch]$Check
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$srcRoot = Join-Path $root 'app\src\main\java\com\personal\flowreader'
$testRoot = Join-Path $root 'app\src\test\java\com\personal\flowreader'
$agentDir = Join-Path $root 'docs\agent'
$indexDir = Join-Path $agentDir 'index'

$mods = '(?:(?:public|internal|private|protected|data|sealed|enum|abstract|open|inline|value|annotation|suspend|const|override|operator|infix|tailrec|lateinit|fun)\s+)*'
$topDecl = [regex]"^$mods(class|object|interface|fun|val|var|typealias)\s+(?:<[^>]+>\s+)?(?:[\w.<>?, ]+\.)?(\w+)"
$memberDecl = [regex]"^    $mods(fun|class|object|interface)\s+(?:<[^>]+>\s+)?(?:[\w.<>?, ]+\.)?(\w+)"

function Get-Entries($file) {
  $lines = [IO.File]::ReadAllLines($file.FullName)
  $large = $lines.Length -gt $MemberThreshold
  $top = New-Object System.Collections.Generic.List[string]
  $members = New-Object System.Collections.Generic.List[string]
  for ($i = 0; $i -lt $lines.Length; $i++) {
    $line = $lines[$i]
    $m = $topDecl.Match($line)
    if ($m.Success) {
      $kind = $m.Groups[1].Value
      $isPrivate = $line -match '^\s*private\s'
      if (-not $isPrivate -or ($large -and $kind -notin 'val', 'var')) {
        $name = $m.Groups[2].Value
        $tag = switch ($kind) { 'class' { if ($line -match '\benum\s+class') { 'enum ' } elseif ($line -match '\bdata\s+class') { 'data ' } elseif ($line -match '\bsealed\s') { 'sealed ' } else { 'class ' } } 'interface' { 'iface ' } 'object' { 'obj ' } default { '' } }
        $top.Add("$tag$name`:$($i + 1)")
      }
      continue
    }
    if ($large) {
      $mm = $memberDecl.Match($line)
      if ($mm.Success) { $members.Add("$($mm.Groups[2].Value):$($i + 1)") }
    }
  }
  [pscustomobject]@{ Lines = $lines.Length; Top = $top; Members = $members }
}

function Get-Group($rel) {
  $parts = $rel.Split('/')
  if ($parts.Length -eq 1) { return 'root' }
  if ($parts[0] -in 'ui', 'plugin' -and $parts.Length -gt 2) { return "$($parts[0])/$($parts[1])" }
  $parts[0]
}

$outputs = [ordered]@{}
$groups = [ordered]@{}
$files = Get-ChildItem $srcRoot -Recurse -File -Filter *.kt | Sort-Object DirectoryName, Name
$total = 0
foreach ($file in $files) {
  $rel = $file.FullName.Substring($srcRoot.Length + 1).Replace('\', '/')
  $g = Get-Group $rel
  if (-not $groups.Contains($g)) { $groups[$g] = [pscustomobject]@{ Sb = New-Object System.Text.StringBuilder; Files = 0; Lines = 0; Dir = $null } }
  $grp = $groups[$g]
  $dir = if ($rel.Contains('/')) { $rel.Substring(0, $rel.LastIndexOf('/')) } else { '(root)' }
  if ($dir -ne $grp.Dir) {
    [void]$grp.Sb.AppendLine()
    [void]$grp.Sb.AppendLine("## $dir")
    [void]$grp.Sb.AppendLine()
    $grp.Dir = $dir
  }
  $e = Get-Entries $file
  $total += $e.Lines
  $grp.Files++
  $grp.Lines += $e.Lines
  $big = if ($e.Lines -gt $MemberThreshold) { ' **large**' } else { '' }
  $decls = if ($e.Top.Count) { ' - ' + ($e.Top -join ', ') } else { '' }
  [void]$grp.Sb.AppendLine("- ``$($file.Name)`` ($($e.Lines))$big$decls")
  if ($e.Members.Count) { [void]$grp.Sb.AppendLine("  - members: " + ($e.Members -join ', ')) }
}

$router = New-Object System.Text.StringBuilder
[void]$router.AppendLine('# Code index (generated)')
[void]$router.AppendLine()
[void]$router.AppendLine('Generated by `scripts/gen-agent-index.ps1`; do not edit. Open the one package file you need.')
[void]$router.AppendLine('Paths are relative to `app/src/main/java/com/personal/flowreader/`. Format: `name:line`; files')
[void]$router.AppendLine("over $MemberThreshold lines also list members, so Read with offset/limit instead of the whole file.")
[void]$router.AppendLine('Hand-written guide: [map.md](map.md).')
[void]$router.AppendLine()
[void]$router.AppendLine('| Package | Index | Files | Lines |')
[void]$router.AppendLine('| --- | --- | --- | --- |')
foreach ($g in $groups.Keys) {
  $slug = $g.Replace('/', '-')
  $grp = $groups[$g]
  $head = "# Code index: $g (generated)`n`nGenerated by ``scripts/gen-agent-index.ps1``; do not edit. Router: [../index.md](../index.md).`n"
  $outputs["index\$slug.md"] = $head + $grp.Sb.ToString()
  [void]$router.AppendLine("| ``$g`` | [index/$slug.md](index/$slug.md) | $($grp.Files) | $($grp.Lines) |")
}
$tests = New-Object System.Text.StringBuilder
[void]$tests.AppendLine('# Tests (generated)')
[void]$tests.AppendLine()
[void]$tests.AppendLine('Paths relative to `app/src/test/java/com/personal/flowreader/`. Router: [../index.md](../index.md).')
[void]$tests.AppendLine()
$testFiles = Get-ChildItem $testRoot -Recurse -File -Filter *.kt | Sort-Object FullName
foreach ($t in $testFiles) { [void]$tests.AppendLine("- ``$($t.FullName.Substring($testRoot.Length + 1).Replace('\', '/'))``") }
$outputs['index\tests.md'] = $tests.ToString()
[void]$router.AppendLine("| tests | [index/tests.md](index/tests.md) | $($testFiles.Count) | |")
[void]$router.AppendLine()
[void]$router.AppendLine("Totals: $($files.Count) main files, $total lines.")
$outputs['index.md'] = $router.ToString()

$stale = @()
foreach ($k in $outputs.Keys) {
  $path = Join-Path $agentDir $k
  $content = $outputs[$k].Replace("`r`n", "`n")
  $existing = if (Test-Path $path) { [IO.File]::ReadAllText($path).Replace("`r`n", "`n") } else { $null }
  if ($existing -ne $content) {
    $stale += $k
    if (-not $Check) {
      New-Item -ItemType Directory -Force (Split-Path $path -Parent) | Out-Null
      [IO.File]::WriteAllText($path, $content)
    }
  }
}
$expected = $outputs.Keys | Where-Object { $_ -like 'index\*' } | ForEach-Object { Split-Path $_ -Leaf }
$orphans = if (Test-Path $indexDir) { Get-ChildItem $indexDir -Filter *.md | Where-Object { $_.Name -notin $expected } } else { @() }
if ($Check) {
  if ($stale.Count -or $orphans) { Write-Error "Agent index is stale ($(($stale + @($orphans | ForEach-Object Name)) -join ', ')); run scripts/gen-agent-index.ps1"; exit 1 }
  Write-Host 'Agent index up to date.'
  exit 0
}
$orphans | Remove-Item
Write-Host "Wrote $($stale.Count) index file(s) ($($files.Count) files, $total lines)."
