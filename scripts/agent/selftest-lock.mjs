// Selftest cases: edit lock, expiry, /takeover, subagents, edit tools.
import { existsSync, readFileSync, utimesSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { cli, commitAll, fwd, hook, readJsonFile, stateFile } from './selftest-lib.mjs';
import { base, clearLock, edit, pre, prompt, setLock, subTranscript, write } from './selftest-payloads.mjs';

export async function lockCases(world, t) {
  const { app, plugins, chats } = world.roots;
  const A = 'conv-a';
  const B = 'conv-b';

  t.section('Lock: two chats competing');
  let r = hook(world, 'hook-preToolUse', edit(world, A, 'StrReplace', join(app, 'src/a.txt')));
  t.eq('A edits app: allowed', r.json, { permission: 'allow' });
  t.eq('A holds the app lock', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, A);
  t.eq('edit logged for A', readFileSync(stateFile(app, 'edits', `${A}.txt`), 'utf8'), 'src/a.txt\n');
  r = hook(world, 'hook-preToolUse', edit(world, B, 'Write', join(app, 'src/new.txt')));
  t.eq('B edits app: denied', r.json?.permission, 'deny');
  t.check('deny names another chat and /takeover', /another chat \(last active \d\d:\d\d\).*\/takeover/.test(r.json?.user_message || ''), r.stdout);
  t.check('agent message says do not edit another way', /Do not edit files another way/.test(r.json?.agent_message || ''), r.stdout);
  t.eq('B edits chats: allowed (no lock)', hook(world, 'hook-preToolUse', edit(world, B, 'Write', join(chats, 'note.md'))).json, { permission: 'allow' });
  t.eq('chats edit logged', readFileSync(stateFile(chats, 'edits', `${B}.txt`), 'utf8'), 'note.md\n');
  t.eq('chats has no lock', existsSync(stateFile(chats, 'lock.json')), false);
  t.eq('B edits plugins: allowed (own lock)', hook(world, 'hook-preToolUse', edit(world, B, 'StrReplace', join(plugins, 'src/a.txt'))).json, { permission: 'allow' });
  t.eq('A edits again: allowed', hook(world, 'hook-preToolUse', edit(world, A, 'StrReplace', join(app, 'src/a.txt'))).json, { permission: 'allow' });

  t.section('Lock: edit tools and CallDynamicTool');
  r = hook(world, 'hook-preToolUse', pre(world, B, 'CallDynamicTool', { namespace: 'cursor', toolName: 'Delete', arguments: { path: fwd(join(app, 'docs/b.md')) } }));
  t.eq('Delete through CallDynamicTool by non-holder: denied', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', pre(world, A, 'CallDynamicTool', { namespace: 'cursor', toolName: 'Delete', arguments: JSON.stringify({ path: fwd(join(app, 'docs/b.md')) }) }));
  t.eq('Delete through CallDynamicTool (arguments as JSON string) by holder: allowed', r.json?.permission, 'allow');
  t.check('that delete was logged', readFileSync(stateFile(app, 'edits', `${A}.txt`), 'utf8').includes('docs/b.md'));
  r = hook(world, 'hook-preToolUse', pre(world, B, 'Delete', { path: fwd(join(app, 'docs/b.md')) }));
  t.eq('direct Delete by non-holder: denied', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', pre(world, B, 'EditNotebook', { target_notebook: fwd(join(app, 'x.ipynb')), cell_idx: 0 }));
  t.eq('EditNotebook (target_notebook) by non-holder: denied', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', pre(world, B, 'CallDynamicTool', { namespace: 'cursor', toolName: 'EditNotebook', arguments: { target_notebook: fwd(join(app, 'x.ipynb')) } }));
  t.eq('EditNotebook through CallDynamicTool: denied', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', pre(world, B, 'CallDynamicTool', { namespace: 'cursor', toolName: 'WebFetch', arguments: { url: 'https://example.test' } }));
  t.eq('non-writing CallDynamicTool: allowed', r.json, { permission: 'allow' });
  r = hook(world, 'hook-preToolUse', pre(world, B, 'ApplyPatch', { input: `*** Begin Patch\n*** Update File: ${fwd(join(app, 'src/a.txt'))}\n*** End Patch` }));
  t.eq('ApplyPatch header path: denied', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', edit(world, B, 'Write', join(world.outside, 'x.txt')));
  t.eq('edit outside the three repos: allowed', r.json, { permission: 'allow' });
  r = hook(world, 'hook-preToolUse', pre(world, B, 'Write', { path: 'src/a.txt' }));
  t.eq('relative path resolved against cwd (app): denied', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', edit(world, A, 'Write', join(world.home, '.cursor', 'hooks.json')));
  t.eq('write to hooks.json: denied even for the holder', r.json?.permission, 'deny');
  r = hook(world, 'hook-preToolUse', edit(world, A, 'Write', join(world.home, '.cursor', 'hooks', 'flow-agent', 'hook-lib.mjs')));
  t.eq('write under hooks/flow-agent: denied', r.json?.permission, 'deny');

  t.section('Lock: expiry');
  clearLock(app);
  write(app, 'src/a.txt', 'changed by A\n');
  write(app, 'caf\u00e9.md', 'accent\n');
  setLock(app, A, 40);
  writeFileSync(stateFile(app, 'edits', `${A}.txt`), 'src/a.txt\ncaf\u00e9.md\n');
  r = hook(world, 'hook-preToolUse', edit(world, B, 'StrReplace', join(app, 'README.md')));
  t.eq('expired lock, previous holder left changes: denied', r.json?.permission, 'deny');
  t.check('message names the uncommitted files', /previous chat's lock expired.*src\/a\.txt.*caf\u00e9\.md/.test(r.json?.user_message || ''), r.stdout);
  t.check('stdout is ASCII with the accent escaped', !/[^\x00-\x7f]/.test(r.stdout) && r.stdout.includes('\\u00e9'), r.stdout);
  commitAll(app, 'A committed');
  r = hook(world, 'hook-preToolUse', edit(world, B, 'StrReplace', join(app, 'README.md')));
  t.eq('expired lock, previous holder clean: B takes it', r.json, { permission: 'allow' });
  t.eq('B now holds the lock', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, B);

  t.section('Lock: /takeover');
  setLock(app, A, 1);
  write(app, 'src/a.txt', 'dirty from A\n');
  writeFileSync(stateFile(app, 'edits', `${A}.txt`), 'src/a.txt\n');
  r = hook(world, 'hook-beforeSubmitPrompt', prompt(world, B, 'hello'));
  t.eq('plain prompt: continue', r.json, { continue: true });
  t.eq('plain prompt does not take the lock', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, A);
  r = hook(world, 'hook-beforeSubmitPrompt', prompt(world, B, '/takeover'));
  t.eq('/takeover: continue', r.json, { continue: true });
  t.eq('/takeover moves the app lock', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, B);
  const log = readFileSync(stateFile(app, 'log.jsonl'), 'utf8').trim().split('\n').map((l) => JSON.parse(l)).filter((e) => e.event === 'takeover');
  t.check('takeover logged with previous holder and its dirty files', log.length === 1 && log[0].from === A && log[0].dirty.includes('src/a.txt'), JSON.stringify(log));
  setLock(plugins, A, 1);
  hook(world, 'hook-beforeSubmitPrompt', prompt(world, B, 'Please continue [flow-takeover] now'));
  t.eq('[flow-takeover] marker moves the plugins lock', readJsonFile(stateFile(plugins, 'lock.json'))?.conversation_id, B);
  commitAll(app);

  t.section('Lock: one editing subagent per chat');
  const parent = 'conv-parent';
  clearLock(app);
  const subEdit = (sub, path, own = true) => pre(world, own ? `own-${sub}` : parent, 'StrReplace', { path: fwd(path) }, { transcript_path: subTranscript(parent, sub) });
  r = hook(world, 'hook-preToolUse', subEdit('sub-1', join(app, 'src/a.txt')));
  t.eq('subagent 1 edits: allowed', r.json, { permission: 'allow' });
  t.eq('lock identity is the parent chat', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, parent);
  t.eq('claim stored', readJsonFile(stateFile(app, 'subagent.json'))?.subagent_id, 'sub-1');
  t.check('edit logged under the parent', readFileSync(stateFile(app, 'edits', `${parent}.txt`), 'utf8').includes('src/a.txt'));
  r = hook(world, 'hook-preToolUse', subEdit('sub-2', join(app, 'src/a.txt'), false));
  t.eq('subagent 2 edits: denied', r.json?.permission, 'deny');
  t.check('message says wait for the other subagent', /Another subagent of this chat is editing flow-reader\. Wait for it to finish\./.test(r.json?.user_message || ''), r.stdout);
  t.eq('the parent itself can still edit', hook(world, 'hook-preToolUse', edit(world, parent, 'StrReplace', join(app, 'src/a.txt'))).json?.permission, 'allow');
  hook(world, 'hook-subagentStop', base(world, 'own-sub-1', 'subagentStop', { transcript_path: subTranscript(parent, 'sub-1'), modified_files: [fwd(join(app, 'src/a.txt'))] }));
  t.eq('subagentStop releases the claim', existsSync(stateFile(app, 'subagent.json')), false);
  r = hook(world, 'hook-preToolUse', subEdit('sub-2', join(app, 'src/a.txt'), false));
  t.eq('subagent 2 edits after release: allowed', r.json, { permission: 'allow' });
  const claimFile = stateFile(app, 'subagent.json');
  const stale = JSON.parse(readFileSync(claimFile, 'utf8'));
  stale.last_active_at = new Date(Date.now() - 11 * 60000).toISOString();
  writeFileSync(claimFile, JSON.stringify(stale));
  r = hook(world, 'hook-preToolUse', subEdit('sub-3', join(app, 'src/a.txt'), false));
  t.eq('claim idle for 11 minutes lapses', r.json, { permission: 'allow' });

  t.section('Lock: mutex and release');
  clearLock(app);
  writeFileSync(stateFile(app, 'lock.mutex'), 'x');
  const old = new Date(Date.now() - 20000);
  utimesSync(stateFile(app, 'lock.mutex'), old, old);
  r = hook(world, 'hook-preToolUse', edit(world, A, 'StrReplace', join(app, 'src/a.txt')));
  t.eq('stale mutex (older than 5 s) is cleared', r.json, { permission: 'allow' });
  t.eq('mutex removed afterwards', existsSync(stateFile(app, 'lock.mutex')), false);
  r = hook(world, 'hook-sessionEnd', base(world, A, 'sessionEnd', { session_id: A, reason: 'completed' }));
  t.eq('sessionEnd reason=completed keeps the lock', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, A);
  hook(world, 'hook-sessionEnd', base(world, B, 'sessionEnd', { session_id: B, reason: 'user_close' }));
  t.eq('sessionEnd by a non-holder keeps the lock', readJsonFile(stateFile(app, 'lock.json'))?.conversation_id, A);
  hook(world, 'hook-sessionEnd', base(world, A, 'sessionEnd', { session_id: A, reason: 'window_close' }));
  t.eq('sessionEnd reason=window_close releases the holder', existsSync(stateFile(app, 'lock.json')), false);
  setLock(app, A, 0);
  t.check('lock.mjs release by a non-holder is refused', cli(world, 'lock', ['release', '--conversation', B]).status === 1);
  const rel = cli(world, 'lock', ['release', '--conversation', A]);
  t.check('lock.mjs release by the holder works', rel.status === 0 && !existsSync(stateFile(app, 'lock.json')), rel.out);
  setLock(app, A, 0);
  const forced = cli(world, 'lock', ['release', '--force']);
  t.check('lock.mjs release --force works from a terminal', forced.status === 0 && !existsSync(stateFile(app, 'lock.json')), forced.out);
  setLock(app, A, 0);
  t.check('lock.mjs status shows the holder', /held by conv-a \(this chat\)/.test(cli(world, 'lock', ['status', '--conversation', A]).out));
  clearLock(app);
  clearLock(plugins);
}
